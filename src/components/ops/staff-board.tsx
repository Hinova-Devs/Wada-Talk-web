"use client";
import { useRouter } from "next/navigation";
import { type FormEvent, useState } from "react";
import { toCents, usd } from "@/lib/ops/access";
import { opsRpc } from "@/lib/ops/call";

/** One row of `ops_staff_list()`. Counts come as numbers or strings (bigint), so they are wrapped in Number(). */
export type StaffRow = {
  user_id: string; email: string; name: string; role: "teacher" | "finance"; pay_per_unit_cents: number;
  planned: number; generated: number; last_active: string | null; owed_cents: number;
};
const day = (iso: string | null) => (iso ? new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "short" }).format(new Date(iso)) : "Never");

/** The directory of Hinova's own team: teachers who plan and generate units, and finance. Add, remove, pay. */
export function StaffBoard({ rows, loadFailed }: { rows: StaffRow[]; loadFailed: boolean }) {
  const router = useRouter();
  const [adding, setAdding] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);
  const [message, setMessage] = useState<{ ok: boolean; text: string } | null>(null);

  async function run(key: string, fn: string, args: Record<string, unknown>, done: string) {
    setBusy(key);
    setMessage(null);
    try {
      await opsRpc(fn, args);
      setMessage({ ok: true, text: done });
      router.refresh();
      return true;
    } catch (e) {
      setMessage({ ok: false, text: e instanceof Error ? e.message : "Something went wrong." });
      return false;
    } finally {
      setBusy(null);
    }
  }

  async function add(e: FormEvent<HTMLFormElement>) {
    e.preventDefault();
    const f = new FormData(e.currentTarget);
    const rate = toCents(String(f.get("rate") || "0"));
    if (rate === null) return setMessage({ ok: false, text: "The pay per unit must be a number like 15 or 12.50." });
    const name = String(f.get("name")).trim();
    const ok = await run("add", "ops_staff_set", { p_email: String(f.get("email")).trim(), p_role: f.get("role"), p_name: name, p_pay_per_unit_cents: rate }, `${name} was added.`);
    if (ok) setAdding(false);
  }

  const pay = (s: StaffRow) => {
    const owed = Number(s.owed_cents);
    if (!confirm(`Record a payout of ${usd(owed)} to ${s.name}? It is added to Finance.`)) return;
    void run(s.user_id, "ops_finance_add", { p_kind: "payout", p_category: "Teacher pay", p_amount_cents: owed, p_party: s.email, p_note: `Units generated by ${s.name}` }, `Payout of ${usd(owed)} recorded in Finance.`);
  };
  const remove = (s: StaffRow) => {
    if (confirm(`Remove ${s.name}? They lose access to ops. Their past work stays.`)) void run(s.user_id, "ops_staff_remove", { p_user: s.user_id }, `${s.name} was removed.`);
  };

  return (
    <>
      <header className="oa-page-head">
        <div>
          <span>Super admin</span>
          <h1>Staff</h1>
          <p>Teachers plan and generate units; finance records money. Only you publish. Owed = units generated × rate, minus payouts.</p>
        </div>
        <div className="oa-page-actions">
          <button type="button" className="oa-button primary" onClick={() => setAdding((v) => !v)}>{adding ? "Cancel" : "＋ Add staff"}</button>
        </div>
      </header>
      {message && <div className={message.ok ? "oa-preview-banner" : "oa-empty"} role="status">{message.text}</div>}
      {adding && (
        <form className="oa-panel ops-add" onSubmit={add}>
          <div>
            <label>Full name<input name="name" required maxLength={120} /></label>
            <label>Email (they must have signed up on this site)<input name="email" type="email" required /></label>
            <label>Role<select name="role"><option value="teacher">Teacher</option><option value="finance">Finance</option></select></label>
            <label>Pay per generated unit (USD)<input name="rate" inputMode="decimal" placeholder="0" /></label>
          </div>
          <button className="oa-button primary" disabled={busy === "add"}>{busy === "add" ? "Adding…" : "Add"}</button>
        </form>
      )}
      {loadFailed ? (
        <div className="oa-empty">Could not load the staff. Refresh, or check that the latest backend migration is applied.</div>
      ) : rows.length === 0 ? (
        <div className="oa-empty">No staff yet. Ask a teacher to create an account on this site, then add them here.</div>
      ) : (
        <section className="oa-panel">
          <table className="oa-table">
            <thead>
              <tr><th>Name</th><th>Role</th><th>Planned</th><th>Generated</th><th>Last active</th><th>Rate</th><th>Owed</th><th /></tr>
            </thead>
            <tbody>
              {rows.map((s) => (
                <tr key={s.user_id}>
                  <td><b>{s.name}</b><br /><small>{s.email}</small></td>
                  <td>{s.role === "teacher" ? "Teacher" : "Finance"}</td>
                  <td>{Number(s.planned)}</td>
                  <td>{Number(s.generated)}</td>
                  <td>{day(s.last_active)}</td>
                  <td>{usd(s.pay_per_unit_cents)}</td>
                  <td>{usd(Number(s.owed_cents))}</td>
                  <td>
                    <span className="ops-inline-form">
                      {Number(s.owed_cents) > 0 && <button type="button" className="oa-button ghost" disabled={busy === s.user_id} onClick={() => pay(s)}>Pay</button>}
                      <button type="button" className="oa-button ghost" disabled={busy === s.user_id} onClick={() => remove(s)}>Remove</button>
                    </span>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      )}
    </>
  );
}
