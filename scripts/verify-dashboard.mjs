import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const source = readFileSync('src/lib/portal/data.ts', 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022}}).outputText;
const {csv, errorMessage, isPortalSection} = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'));
const report = csv([{user_id: 'id', first_name: '=SUM(1,2)', current_unit: {position: 0, title: 'Unit "one", intro'}, calls: 0, units_done: 0, first_score: null, latest_score: null, streak: 0, email: 'private@example.com', transcript: 'PRIVATE TRANSCRIPT', said: 'PRIVATE MISTAKE'}]);
assert.ok(report.includes('"\'=SUM(1,2)"'));
assert.ok(report.includes('"Unit ""one"", intro"'));
assert.ok(report.includes('"0"'));
assert.ok(!report.includes('private@example.com') && !report.includes('PRIVATE'));
assert.equal(csv([]).split('\r\n').length, 1);
assert.equal(errorMessage('last_admin'), 'Make someone else admin first');
assert.equal(errorMessage('not_allowed'), "You don't have access to this");
assert.equal(isPortalSection('audit'), true);
for (const removed of ['settings', 'reports', 'talk-hours', 'discussions']) assert.equal(isPortalSection(removed), false);
console.log('PASS: CSV quoting, formula protection, privacy, empty export, API errors and supported sections.');
const authSource = readFileSync('src/lib/portal/auth.ts', 'utf8');
const authCompiled = ts.transpileModule(authSource, {compilerOptions: {module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022}}).outputText;
const {usesDemoPassword, authErrorMessage, signInStaff} = await import('data:text/javascript;base64,' + Buffer.from(authCompiled).toString('base64'));
assert.equal(usesDemoPassword(' SAHRA@demo.wada.test ', true), true);
assert.equal(usesDemoPassword('sahra@demo.wada.test', false), false);
assert.equal(usesDemoPassword('teacher@school.so', true), false);
const calls = [];
const authClient = {auth: {signInWithPassword: async input => {calls.push(['password', input]); return {error: null};}, signInWithOtp: async input => {calls.push(['otp', input]); return {error: null};}}};
await signInStaff(authClient, {email: ' SAHRA@demo.wada.test ', password: 'entered-password', development: true, origin: 'http://localhost:3000'});
assert.deepEqual(calls.pop(), ['password', {email: 'sahra@demo.wada.test', password: 'entered-password'}]);
await signInStaff(authClient, {email: ' Teacher@School.so ', password: '', development: true, origin: 'http://localhost:3000'});
assert.deepEqual(calls.pop(), ['otp', {email: 'teacher@school.so', options: {emailRedirectTo: 'http://localhost:3000', shouldCreateUser: false}}]);
await signInStaff(authClient, {email: 'sahra@demo.wada.test', password: 'never-used', development: false, origin: 'https://admin.wada.com'});
assert.deepEqual(calls.pop(), ['otp', {email: 'sahra@demo.wada.test', options: {emailRedirectTo: 'https://admin.wada.com', shouldCreateUser: false}}]);
assert.match(authErrorMessage({code: 'email_address_not_authorized', message: 'API error'}), /email sender/);
assert.match(authErrorMessage({code: 'over_email_send_rate_limit', message: 'API error'}), /limit/);
assert.match(authErrorMessage({code: 'signup_disabled', message: 'API error'}), /invite/);
assert.match(authErrorMessage({code: 'bad_code_verifier', message: 'API error'}), /same browser/);
assert.match(authErrorMessage({status: 500, message: 'API error'}), /email delivery/);
assert.equal(authErrorMessage({code: 'invalid_credentials', message: 'API error'}), 'The email or password is incorrect.');
console.log('PASS: staff OTP stays invitation-only, production excludes demo password login, development seed login and specific authentication errors.');
const institutionSource = readFileSync('src/lib/portal/institution.ts', 'utf8');
const institutionCompiled = ts.transpileModule(institutionSource, {compilerOptions: {module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022}}).outputText;
const {institutionType, portalLabel} = await import('data:text/javascript;base64,' + Buffer.from(institutionCompiled).toString('base64'));
assert.equal(institutionType('school'), 'school');
assert.equal(institutionType('admin'), 'university');
assert.equal(portalLabel('classes', 'school', 'fallback'), 'Classes');
assert.equal(portalLabel('classes', 'university', 'fallback'), 'Course groups');
assert.equal(portalLabel('team', 'university', 'fallback'), 'Lecturers & admins');
assert.ok(isPortalSection('join-codes') && isPortalSection('institution'));
console.log('PASS: Institution selection and institution-specific navigation.');
